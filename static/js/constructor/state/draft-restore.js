/**
 * Чистая логика решения о восстановлении черновика из localStorage (H3).
 *
 * Снимок-черновик хранится в localStorage под ключом с act_id (см.
 * StorageManager.saveState) и содержит метаданные (savedAt,
 * baseContentVersion; baseUpdatedAt — справочное) + данные
 * AppState.exportData(). Восстановление предлагается без вопросов ТОЛЬКО
 * если контент акта с момента снимка никто не менял: серверный
 * acts.content_version равен baseContentVersion снимка. Счётчик
 * инкрементируется бэкендом исключительно при записи КОНТЕНТА — правки
 * метаданных и соседних частей КМ его не трогают и черновик не
 * инвалидируют (прежняя сверка по updated_at давала на них ложные
 * конфликты). Расхождение версий = контент менялся, и судьбу правок
 * решает пользователь через диалог конфликта ('conflict'), а не
 * молчаливое удаление.
 */

/**
 * Решает судьбу снимка-черновика при загрузке акта.
 *
 * @param {Object|null} snapshot Снимок из localStorage ({actId, savedAt,
 *   baseContentVersion, data}) или null, если снимка нет
 * @param {number|null} serverContentVersion Серверный acts.content_version
 *   из metadata GET-контента (0 — валидное значение)
 * @returns {'restore'|'conflict'|'discard'|'none'}
 *   'restore'  — предложить восстановление (контент не менялся с момента
 *               снимка); несогласованные снимки тоже восстанавливаются —
 *               их чинит sanitizeActContent на пути загрузки (#10, Variant Б);
 *   'conflict' — снимок структурно валиден, но контент с момента снимка
 *               менялся (версии расходятся): судьбу правок решает
 *               пользователь через диалог конфликта, снимок молча НЕ удаляется;
 *   'discard'  — молча удалить снимок (структурно повреждён — нет
 *               данных/дерева, либо нет версий и сверить их нельзя);
 *   'none'     — снимка нет, делать нечего.
 */
export function shouldOfferRestore(snapshot, serverContentVersion) {
    if (!snapshot) {
        return 'none';
    }
    // Повреждённый снимок (нет данных или дерева) восстановлению не подлежит.
    if (!snapshot.data || typeof snapshot.data !== 'object' || !snapshot.data.tree) {
        return 'discard';
    }
    // #10 (Variant Б): семантически несогласованный снимок (сироты словарей /
    // висячие ссылки узлов) НЕ выбрасываем — восстанавливаем и чиним неразрушающе.
    // Восстановленные данные подставляются в content, а штатный путь загрузки
    // прогоняет sanitizeActContent (api.js) — те же инварианты, что чинит зеркало
    // isSnapshotConsistent, но без потери несохранённых правок пользователя.
    // Проверка версий — Number.isInteger, НЕ truthiness: 0 — валидная версия
    // (акт ещё ни разу не сохранял контент). Без обеих версий сравнить
    // «менялся ли контент» невозможно — считаем снимок структурно битым.
    if (!Number.isInteger(snapshot.baseContentVersion)
        || !Number.isInteger(serverContentVersion)) {
        return 'discard';
    }
    // Расхождение версий = контент менялся после снимка. Это НЕ повод молча
    // уничтожать правки пользователя — отдаём вердикт 'conflict', и решение
    // (версия БД или черновик) принимает пользователь в явном диалоге.
    return snapshot.baseContentVersion === serverContentVersion ? 'restore' : 'conflict';
}

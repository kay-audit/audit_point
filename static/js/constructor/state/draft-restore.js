/**
 * Чистая логика решения о восстановлении черновика из localStorage (H3).
 *
 * Снимок-черновик хранится в localStorage под ключом с act_id (см.
 * StorageManager.saveState) и содержит метаданные (savedAt, baseUpdatedAt)
 * + данные AppState.exportData(). Восстановление предлагается без вопросов
 * ТОЛЬКО если акт с момента снимка никто не менял: серверный updated_at
 * равен baseUpdatedAt снимка. Любое сохранение акта (содержимого или
 * метаданных, самим пользователем с другого места или кем-то ещё) бампит
 * updated_at на сервере — такой снимок конфликтует с версией БД, и судьбу
 * правок решает пользователь через диалог конфликта ('conflict'), а не
 * молчаливое удаление.
 */

/**
 * Сравнивает две временные метки на равенство момента времени.
 *
 * Сначала строгое строковое равенство (оба значения приходят из одного
 * pydantic-сериализатора и для одного момента совпадают посимвольно),
 * затем сравнение распарсенных эпох — на случай разной записи одного
 * и того же момента (например, с/без дробной части секунд).
 *
 * @param {string} a Первая метка (ISO-строка)
 * @param {string} b Вторая метка (ISO-строка)
 * @returns {boolean} true если метки указывают на один момент времени
 */
function sameInstant(a, b) {
    if (a === b) return true;
    const ta = Date.parse(a);
    const tb = Date.parse(b);
    return Number.isFinite(ta) && Number.isFinite(tb) && ta === tb;
}

/**
 * Решает судьбу снимка-черновика при загрузке акта.
 *
 * @param {Object|null} snapshot Снимок из localStorage ({actId, savedAt,
 *   baseUpdatedAt, data}) или null, если снимка нет
 * @param {string|null} serverUpdatedAt Серверный updated_at акта из GET-контента
 * @returns {'restore'|'conflict'|'discard'|'none'}
 *   'restore'  — предложить восстановление (акт не менялся с момента снимка);
 *               несогласованные снимки тоже восстанавливаются — их чинит
 *               sanitizeActContent на пути загрузки (#10, Variant Б);
 *   'conflict' — снимок структурно валиден, но акт с момента снимка менялся
 *               (метки расходятся): судьбу правок решает пользователь через
 *               диалог конфликта, снимок молча НЕ удаляется;
 *   'discard'  — молча удалить снимок (структурно повреждён — нет
 *               данных/дерева, либо нет меток и сверить их нельзя);
 *   'none'     — снимка нет, делать нечего.
 */
export function shouldOfferRestore(snapshot, serverUpdatedAt) {
    if (!snapshot) {
        return 'none';
    }
    // Повреждённый снимок (нет данных или дерева) восстановлению не подлежит.
    if (!snapshot.data || typeof snapshot.data !== 'object' || !snapshot.data.tree) {
        return 'discard';
    }
    // #10 (Variant Б): семантически несогласованный снимок (сироты словарей /
    // висячие ссылки узлов) НЕ выбрасываем — восстанавливаем и чиним неразрушающе.
    // Восстановленные данные подставляются в content, а штатный путь загрузки
    // прогоняет sanitizeActContent (api.js) — те же инварианты, что чинит зеркало
    // isSnapshotConsistent, но без потери несохранённых правок пользователя.
    // Без обеих меток сравнить «менялся ли акт» невозможно — восстанавливать
    // такой снимок не из чего решать, считаем его структурно битым.
    if (!snapshot.baseUpdatedAt || !serverUpdatedAt) {
        return 'discard';
    }
    // Расхождение меток = акт менялся после снимка. Это НЕ повод молча
    // уничтожать правки пользователя — отдаём вердикт 'conflict', и решение
    // (версия БД или черновик) принимает пользователь в явном диалоге.
    return sameInstant(snapshot.baseUpdatedAt, serverUpdatedAt) ? 'restore' : 'conflict';
}

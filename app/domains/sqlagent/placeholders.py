# --- Общая завершающая фраза ---------------------------------------------
# Одинаковая для всех инструментов: про «внешнюю сеть» и ЕРМ в КАП.
# Подставляется шаблоном после tool-специфичных абзацев.

COMMON_AVAILABILITY_NOTE: Paragraph = {
    "lead": False,
    "html": (
        "Во&nbsp;внешней сети инструмент недоступен, но&nbsp;будет реализован в&nbsp;"
        "<span class=\"tool-placeholder-highlight\">"
        "Едином рабочем месте аудитора в&nbsp;КАП</span>."
    ),
}


def get_placeholder_paragraphs(tool: str) -> list[Paragraph]:
    """Возвращает абзацы для инструмента + общую завершающую фразу.

    Если инструмент не найден в ``TOOL_PARAGRAPHS`` — возвращается
    только общая завершающая фраза (страница всё равно отрендерится,
    но без описания конкретного инструмента).
    """
    tool_paragraphs = TOOL_PARAGRAPHS.get(tool, [])
    return [*tool_paragraphs, COMMON_AVAILABILITY_NOTE]

"""Бюджет вывода и таймаут одного вызова LLM в text-actions.

Зачем модуль. Ворота ввода подняты до 32768 символов
(``CHAT__TEXT_ACTIONS__MAX_INPUT_CHARS``), а вызов уходил без ``max_tokens`` и с
жёстким таймаутом 60 секунд. Оба значения не зависели от объёма работы, поэтому
длинный ввод ломался молча: у провайдера с низким дефолтным потолком completion'а
ответ обрезался на середине и подставлялся пользователю как готовый текст, а там,
где потолок был высоким, вызов не укладывался в минуту и уходил в
``APITimeoutError`` — с пятью добросовестными повторами заведомо провального
запроса.

Здесь — чистые функции расчёта: сколько токенов разрешить на ответ и сколько
секунд ждать. Значения выведены от длины ИСХОДНОГО текста, потому что это
единственная величина, известная до вызова.

Почему константы, а не настройки. Каждая новая ручка `CHAT__*` заводится
синхронно в трёх env-файлах и в реестре переменных, а крутить эти числа руками
незачем: они описывают не политику, а физику (как русский текст ложится в токены
и как быстро генерирует модель). Настройкой остаётся то, что и было —
``per_call_timeout_sec``, но теперь это НИЖНЯЯ граница ожидания, а не жёсткое
значение.
"""
from __future__ import annotations

import math

# --- Оценка длины в токенах ---------------------------------------------------

# Символов на токен для русского текста (byte-level BPE современных моделей).
# Оценка сознательно консервативная: предельный ввод 32768 символов даёт
# ≈13.1k токенов, то есть верхний край наблюдаемого диапазона 11–14k. Занижать
# число символов на токен безопаснее, чем завышать: ошибка в эту сторону даёт
# запас бюджета, а в обратную — обрезанный ответ.
CHARS_PER_TOKEN = 2.5

# --- Бюджет вывода ------------------------------------------------------------

# Профиль ПЕРЕПИСЫВАЮЩЕГО действия: ответ сопоставим со входом. Запас 15% —
# на то, что правка бывает длиннее исходника: восстановленная пунктуация и
# пробелы у корректора, раскрытые скобки и разбитые предложения у улучшайзера.
PROFILE_REWRITE = "rewrite"
REWRITE_OUTPUT_RATIO = 1.15

# Профиль ИЗВЛЕКАЮЩЕГО действия (формализатор): ответ — JSON-выжимка из текста,
# структурно короче него. Полный «переписывающий» бюджет здесь не нужен и вреден:
# ``max_tokens`` больше остатка контекстного окна провайдеры отдают ошибкой 400.
PROFILE_EXTRACT = "extract"
EXTRACT_OUTPUT_RATIO = 0.6

# Служебные токены сверх полезной нагрузки: обрамление JSON, ключи полей,
# переводы строк, возможный ведущий ярлык.
OUTPUT_OVERHEAD_TOKENS = 256

# Нижняя граница: на коротком выделении бюджет не должен опускаться до величины,
# которой не хватит на пару предложений с разметкой.
MIN_OUTPUT_TOKENS = 512

# Верхняя граница. При предельном вводе расчёт даёт ≈15.3k токенов, то есть кап
# в штатном режиме не срабатывает — он страхует от того, чтобы запрошенный
# ``max_tokens`` не вылез за контекстное окно модели, если ворота ввода когда-то
# поднимут ещё выше.
MAX_OUTPUT_TOKENS = 16384

_OUTPUT_RATIOS = {
    PROFILE_REWRITE: REWRITE_OUTPUT_RATIO,
    PROFILE_EXTRACT: EXTRACT_OUTPUT_RATIO,
}

# --- Таймаут вызова -----------------------------------------------------------

# Консервативная скорость генерации, токенов в секунду. Наблюдаемый диапазон на
# наших маршрутах — 30–60; берём нижний край, потому что таймаут обязан
# переживать медленный день провайдера, а не только хороший.
GENERATION_TOKENS_PER_SEC = 30.0

# Постоянные накладные расходы: очередь провайдера, чтение промпта (prefill),
# сеть, обмен через redis-мост.
TIMEOUT_OVERHEAD_SEC = 15.0

# Потолок расчётной части ожидания. Отдельной ручкой не является: он следует из
# капа бюджета вывода — дольше, чем нужно на ``MAX_OUTPUT_TOKENS``, ждать нечего.
# ≈9.5 минут; настроечный ``per_call_timeout_sec`` остаётся нижней границей и
# капом не срезается.
MAX_ESTIMATED_TIMEOUT_SEC = (
    TIMEOUT_OVERHEAD_SEC + MAX_OUTPUT_TOKENS / GENERATION_TOKENS_PER_SEC
)

# --- Повторные попытки --------------------------------------------------------

# Кап числа попыток для text-actions. Общий ``CHAT__RETRY__MAX_ATTEMPTS`` (5)
# писан под вызовы чата; здесь пользователь ждёт ответа синхронно, а таймаут
# одного вызова теперь считается от объёма текста и на предельном вводе доходит
# до ≈9.5 минут. Пять попыток на таком тексте — это до трёх четвертей часа
# ожидания и пятикратно оплаченный prompt на запросе, который уже показал, что
# не проходит; у формализатора цена ещё умножается на шесть вызовов.
# Именно кап, а не подмена: заданное меньшее значение уважается.
MAX_ATTEMPTS_CAP = 2


def retry_attempts(configured: int) -> int:
    """Число попыток для одного вызова text-action (не больше ``MAX_ATTEMPTS_CAP``)."""
    return max(1, min(int(configured), MAX_ATTEMPTS_CAP))


# --- Признак обрыва ответа ----------------------------------------------------

# Доля исходной длины, ниже которой ответ ПЕРЕПИСЫВАЮЩЕГО действия считается
# обрывом. Корректору промпт прямо запрещает сокращать текст, поэтому ответ
# короче 70% исходника — это не хорошая работа, а потерянный хвост. К
# сокращающим действиям («Пиши, сокращай») правило неприменимо по смыслу.
TRUNCATION_MIN_KEEP_RATIO = 0.7

# Ниже этой длины проверка доли не применяется: на коротком выделении обрыв
# невозможен (в любой потолок ответа такой текст помещается целиком), а разброс
# доли велик.
TRUNCATION_GUARD_MIN_CHARS = 200


def estimate_tokens(chars: int) -> int:
    """Оценка длины текста в токенах по числу символов."""
    if chars <= 0:
        return 0
    return math.ceil(chars / CHARS_PER_TOKEN)


def output_budget_tokens(source_chars: int, *, profile: str = PROFILE_REWRITE) -> int:
    """``max_tokens`` для одного вызова по длине исходного текста.

    ``profile`` — ``PROFILE_REWRITE`` (ответ сопоставим со входом) либо
    ``PROFILE_EXTRACT`` (ответ — выжимка). Неизвестный профиль трактуется как
    переписывающий: ошибиться в сторону большего бюджета безопаснее.
    """
    ratio = _OUTPUT_RATIOS.get(profile, REWRITE_OUTPUT_RATIO)
    raw = estimate_tokens(source_chars) * ratio + OUTPUT_OVERHEAD_TOKENS
    return int(min(max(raw, MIN_OUTPUT_TOKENS), MAX_OUTPUT_TOKENS))


def call_timeout_sec(
    source_chars: int, *, floor_sec: float, profile: str = PROFILE_REWRITE,
) -> float:
    """Таймаут одного вызова: не меньше ``floor_sec`` и растёт с объёмом работы.

    ``floor_sec`` — настройка ``CHAT__TEXT_ACTIONS__PER_CALL_TIMEOUT_SEC``: она
    остаётся нижней границей, чтобы короткое выделение не получило таймаут
    меньше привычного. Сверху расчётная часть ограничена
    ``MAX_ESTIMATED_TIMEOUT_SEC`` — следствием капа бюджета вывода.
    """
    tokens = output_budget_tokens(source_chars, profile=profile)
    estimated = TIMEOUT_OVERHEAD_SEC + tokens / GENERATION_TOKENS_PER_SEC
    return max(float(floor_sec), estimated)


def looks_truncated(source: str, answer: str) -> bool:
    """Похож ли ответ ПЕРЕПИСЫВАЮЩЕГО действия на оборванный.

    Эвристика-подстраховка на провайдеров, которые не сообщают
    ``finish_reason="length"``: ответ, потерявший больше трети исходного объёма,
    отдавать пользователю нельзя. Применять ТОЛЬКО к действиям, которые обязаны
    сохранять объём (корректор орфографии); для сокращающих действий короткий
    ответ — штатный результат.
    """
    src_len = len(source or "")
    if src_len < TRUNCATION_GUARD_MIN_CHARS:
        return False
    return len(answer or "") < src_len * TRUNCATION_MIN_KEEP_RATIO
